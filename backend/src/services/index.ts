import { DocumentRepository } from '../repositories/document.repository';
import { FileRepository } from '../repositories/file.repository';
import { MasterRepository } from '../repositories/master.repository';
import { RefreshTokenRepository } from '../repositories/refreshToken.repository';
import { RoleRepository } from '../repositories/role.repository';
import { UserRepository } from '../repositories/user.repository';
import { UserAddressRepository } from '../repositories/userAddress.repository';
import { VerificationRepository } from '../repositories/verification.repository';
import { VesselRepository } from '../repositories/vessel.repository';
import { VesselImportRepository } from '../repositories/vesselImport.repository';
import { VtmsRepository } from '../repositories/vtms.repository';
import { createAisService } from './ais.service';
import { createAuthService } from './auth.service';
import { createContractService } from './contract.service';
import { createDocumentService } from './document.service';
import { createFileService } from './file.service';
import { createMasterService } from './master.service';
import { createOptionsService } from './options.service';
import { createPortDueService } from './portDue.service';
import { createReportService } from './report.service';
import { createRoleService } from './role.service';
import { createSurveyService } from './survey.service';
import { createTokenService } from './token.service';
import { createUserService } from './user.service';
import { createVesselService } from './vessel.service';
import { createVesselImportService } from './vesselImport.service';
import { createVtmsService } from './vtms.service';

export const userRepository = new UserRepository();
export const roleRepository = new RoleRepository();
export const refreshTokenRepository = new RefreshTokenRepository();
export const verificationRepository = new VerificationRepository();
export const fileRepository = new FileRepository();
export const userAddressRepository = new UserAddressRepository();
export const masterRepository = new MasterRepository();
export const vesselRepository = new VesselRepository();
export const documentRepository = new DocumentRepository();
export const vtmsRepository = new VtmsRepository();
export const vesselImportRepository = new VesselImportRepository();

export const fileService = createFileService(fileRepository);
export const tokenService = createTokenService(refreshTokenRepository, userRepository);
export const roleService = createRoleService(roleRepository, userRepository);
export const userService = createUserService({ users: userRepository, roles: roleRepository, verifications: verificationRepository, files: fileService, tokens: tokenService });
export const authService = createAuthService({ users: userRepository, roles: roleRepository, verifications: verificationRepository, files: fileService, tokens: tokenService, userService });
export const masterService = createMasterService(masterRepository, fileService);
export const optionsService = createOptionsService(masterRepository, roleService, userService);
export const vesselService = createVesselService(vesselRepository, fileService);
export const documentService = createDocumentService(documentRepository, vesselRepository, fileService);
export const vtmsService = createVtmsService(vtmsRepository, documentRepository, vesselRepository, fileService);
export const vesselImportService = createVesselImportService(vesselImportRepository, vesselRepository, documentRepository, vtmsRepository, fileService);
export const portDueService = createPortDueService(documentRepository, fileService);
export const contractService = createContractService(fileService);
export const surveyService = createSurveyService();
export const aisService = createAisService();
export const reportService = createReportService();
